class TestPublish:
    """Test complete publish workflow."""
    
    def test_publish_success(self, publisher, sample_output_dir):
        """Test successful publish workflow."""
        with patch.object(publisher, '_clone_repository'), \
             patch.object(publisher, '_copy_files_to_repo'), \
             patch.object(publisher, '_commit_changes'), \
             patch.object(publisher, '_push_changes'), \
             patch.object(publisher, '_run_git_command') as mock_git:
            
            mock_git.return_value = MagicMock(stdout="abc123", stderr="")
            
            result = publisher.publish(source_dir=sample_output_dir)
            
            assert result["success"] is True
            assert result["commit_hash"] == "abc123"
            assert result["error"] is None
    
    def test_publish_with_custom_message(self, publisher, sample_output_dir):
        """Test publish with custom commit message."""
        with patch.object(publisher, '_clone_repository'), \
             patch.object(publisher, '_copy_files_to_repo'), \
             patch.object(publisher, '_commit_changes') as mock_commit, \
             patch.object(publisher, '_push_changes'):
            
            publisher.publish(
                source_dir=sample_output_dir,
                commit_message="Custom message"
            )
            
            mock_commit.assert_called_once_with("Custom message")
    
    def test_publish_auto_message(self, publisher, sample_output_dir):
        """Test publish with auto-generated commit message."""
        with patch.object(publisher, '_clone_repository'), \
             patch.object(publisher, '_copy_files_to_repo'), \
             patch.object(publisher, '_commit_changes') as mock_commit, \
             patch.object(publisher, '_push_changes'):
            
            publisher.publish(source_dir=sample_output_dir)
            
            # Check that commit message contains timestamp
            call_args = mock_commit.call_args[0][0]
            assert "Update configs" in call_args
    
    def test_publish_git_error(self, publisher, sample_output_dir):
        """Test publish handling Git errors."""
        with patch.object(publisher, '_clone_repository') as mock_clone:
            mock_clone.side_effect = subprocess.CalledProcessError(1, "git", stderr="Auth failed")
            
            result = publisher.publish(source_dir=sample_output_dir)
            
            assert result["success"] is False
            assert result["error"] is not None
            assert "Git command failed" in result["error"]
    
    def test_publish_general_error(self, publisher, sample_output_dir):
        """Test publish handling general errors."""
        with patch.object(publisher, '_clone_repository') as mock_clone:
            mock_clone.side_effect = Exception("Unexpected error")
            
            result = publisher.publish(source_dir=sample_output_dir)
            
            assert result["success"] is False
            assert "Unexpected error" in result["error"]


