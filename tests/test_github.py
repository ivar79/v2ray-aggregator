class TestCloneRepository:
    """Test repository cloning operations."""
    
    def test_clone_new_repository(self, publisher):
        """Test cloning a new repository."""
        with patch.object(publisher, '_run_git_command') as mock_git:
            publisher._clone_repository()
            
            # Should call git clone
            calls = [call[0][0] for call in mock_git.call_args_list]
            assert any("clone" in call for call in calls)
    
    def test_clone_existing_repository(self, publisher):
        """Test updating an existing repository."""
        publisher.local_path.mkdir()
        
        with patch.object(publisher, '_run_git_command') as mock_git:
            publisher._clone_repository()
            
            # Should call git fetch and pull instead of clone
            calls = [call[0][0] for call in mock_git.call_args_list]
            assert any("fetch" in call for call in calls)
            assert any("pull" in call for call in calls)
            assert not any("clone" in call for call in calls)
    
    def test_clone_with_token(self, publisher):
        """Test cloning with authentication token."""
        with patch.object(publisher, '_run_git_command') as mock_git:
            publisher._clone_repository()
            
            # Check if token is used in URL
            calls = [call[0][0] for call in mock_git.call_args_list]
            clone_call = next(call for call in calls if "clone" in call)
            
            # Token should be in the URL
            assert publisher.github_token in str(clone_call)


